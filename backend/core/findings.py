from datetime import datetime, timedelta, timezone
from rapidfuzz.fuzz import ratio
from .models import Window
from .rerank import matches, UNCONFIRMED, REPUTABLE

def research_window(meeting_at, now=None):
    now = now or datetime.now(timezone.utc)
    end = min(meeting_at.astimezone(timezone.utc), now.astimezone(timezone.utc)).date()
    return Window(start=end-timedelta(days=30), end=end)

def finding_status(sources):
    reliable = [s for s in sources if not matches(s.domain,UNCONFIRMED)]
    if any(s.official for s in reliable) or len({s.domain for s in reliable}) >= 2:
        return 'verified'
    if any(matches(s.domain,REPUTABLE) for s in reliable):
        return 'reported'
    return 'unconfirmed'

def clean_findings(findings,sources,window):
    known = {s.id:s for s in sources}
    kept = []
    for item in findings:
        item.source_ids = [sid for sid in item.source_ids if sid in known]
        if not window.start <= item.date <= window.end or not item.source_ids:
            continue
        # Dated evidence, not just a date generated by a model, must be in-window.
        evidence = [known[sid] for sid in item.source_ids if known[sid].published_date and window.start <= known[sid].published_date <= window.end]
        if not evidence:
            continue
        duplicate = next((f for f in kept if abs((f.date-item.date).days) <= 2 and ratio(f.title.casefold(),item.title.casefold()) >= 85),None)
        if duplicate:
            duplicate.source_ids = list(dict.fromkeys(duplicate.source_ids+item.source_ids))
            duplicate.status = finding_status([known[s] for s in duplicate.source_ids])
            continue
        item.status = finding_status([known[s] for s in item.source_ids])
        kept.append(item)
    return kept
